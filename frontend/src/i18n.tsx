interface I18nContextValue {
  language: Language
  t: (key: string, params?: Record<string, string | number>) => string
  formatDateTime: (value: string | null) => string
}

const fallbackContext: I18nContextValue = {
  language: 'en',
  t: (key, params = {}) => {
    const value = translations.en[key] ?? key
    return typeof value === 'function' ? value(params) : value
  },
  formatDateTime: (value) => {
    if (!value) {
      return 'Not available'
    }

    const parsed = new Date(value)
    if (Number.isNaN(parsed.getTime())) {
      return value
    }

    return new Intl.DateTimeFormat('en-US', {
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      hour12: false,
    }).format(parsed)
  },
}

const I18nContext = createContext<I18nContextValue>(fallbackContext)

export function I18nProvider({
  children,
  language,
}: {
  children: ReactNode
  language: Language
}) {
  useEffect(() => {
    const previous = document.documentElement.getAttribute('lang')
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en'
    return () => {
      if (previous === null) document.documentElement.removeAttribute('lang')
      else document.documentElement.lang = previous
    }
  }, [language])

  const t = useCallback(
    (key: string, params: Record<string, string | number> = {}) => {
      const value = translations[language][key] ?? translations.en[key] ?? key
      if (typeof value === 'function') {
        return value(params)
      }
      return value
    },
    [language],
  )

  const formatDateTime = useCallback(
    (value: string | null) => {
      if (!value) {
        return t('common.notAvailable')
      }

      const parsed = new Date(value)
      if (Number.isNaN(parsed.getTime())) {
        return value
      }

      return new Intl.DateTimeFormat(language === 'zh' ? 'zh-CN' : 'en-US', {
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
        hour: '2-digit',
        minute: '2-digit',
        second: '2-digit',
        hour12: false,
      }).format(parsed)
    },
    [language, t],
  )

  const contextValue = useMemo(
    () => ({ language, t, formatDateTime }),
    [formatDateTime, language, t],
  )

  return <I18nContext.Provider value={contextValue}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}
